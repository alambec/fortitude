//! Index schema, generated from [`fortitude_core::attrs::INDEXED`], for SQLite and
//! PostgreSQL.
//!
//! One flat table per level. Every indexed attribute is a column with its own index; person
//! names also get an upper-cased `<column>_key` column for case-insensitive matching.
//! `attrs` holds the pre-encoded QIDO-RS attributes of the level and `rep_instance` the first
//! stored instance, used to answer for attributes that are not indexed.
//!
//! PostgreSQL text columns use the "C" collation: comparisons are bytewise as in SQLite, and
//! their indexes serve `LIKE` prefix patterns.
//!
//! The schema has a version, recorded in the database. Fortitude is not deployed yet, so the
//! schema changes in place: an index of another version is refused, and must be re-created.
//! Once it is deployed, each change will bump the version and add an upgrade.

use fortitude_core::attrs::{self, Kind, Level};

use super::IndexError;
use super::db::{Connection, Dialect};

/// Versions 1 to 3 were development versions, without checksums; version 4 had no
/// `modalities` table, which the upgrade to 5 adds.
const VERSION: i64 = 5;

/// Per-connection SQLite settings.
pub fn configure(conn: &rusqlite::Connection) -> rusqlite::Result<()> {
    conn.execute_batch(
        "PRAGMA journal_mode = WAL;
         PRAGMA synchronous = NORMAL;
         PRAGMA temp_store = MEMORY;
         PRAGMA cache_size = -65536;
         PRAGMA mmap_size = 268435456;
         PRAGMA busy_timeout = 5000;",
    )
}

/// Create the schema of an empty database, or check the version of an existing one.
pub fn migrate(conn: &mut Connection) -> Result<(), IndexError> {
    let dialect = conn.dialect();
    match dialect {
        Dialect::Sqlite => {
            conn.batch("BEGIN IMMEDIATE")?;
            let version = conn.query_row("PRAGMA user_version", &[], |r| r.i64(0))?;
            finish(conn, dialect, version.unwrap_or(0), |conn| {
                conn.batch(&format!("PRAGMA user_version = {VERSION}"))
            })
        }
        Dialect::Postgres => {
            // Serializes servers starting together on an empty database.
            conn.batch(
                "BEGIN;
                 SELECT pg_advisory_xact_lock(7307251207458114655);
                 CREATE TABLE IF NOT EXISTS schema_version (version BIGINT NOT NULL);",
            )?;
            let version =
                conn.query_row("SELECT version FROM schema_version", &[], |r| r.i64(0))?;
            finish(conn, dialect, version.unwrap_or(0), |conn| {
                conn.batch(&format!(
                    "DELETE FROM schema_version; INSERT INTO schema_version VALUES ({VERSION});"
                ))
            })
        }
    }
}

/// Second half of [`migrate`], in its transaction.
fn finish(
    conn: &mut Connection,
    dialect: Dialect,
    version: i64,
    record: impl FnOnce(&mut Connection) -> Result<(), IndexError>,
) -> Result<(), IndexError> {
    let result = match version {
        VERSION => Ok(()),
        0 => conn
            .batch(&ddl(dialect))
            .and_then(|()| conn.batch(&modalities_ddl(dialect)))
            .and_then(|()| record(conn)),
        4 => conn
            .batch(&modalities_ddl(dialect))
            .and_then(|()| record(conn)),
        _ => Err(IndexError::Database(format!(
            "unsupported index schema version {version} (expected {VERSION}): re-create the index"
        ))),
    };
    match result {
        Ok(()) => conn.batch("COMMIT"),
        Err(e) => {
            let _ = conn.batch("ROLLBACK");
            Err(e)
        }
    }
}

/// Columns of indexed attributes of `level`, in [`attrs::INDEXED`] order, person name keys
/// included right after their column.
pub fn columns(level: Level) -> Vec<String> {
    attrs::indexed(level)
        .flat_map(|a| {
            let key = (a.kind == Kind::PersonName).then(|| format!("{}_key", a.column));
            std::iter::once(a.column.to_owned()).chain(key)
        })
        .collect()
}

fn ddl(dialect: Dialect) -> String {
    let (pk, int, text, blob) = match dialect {
        Dialect::Sqlite => ("INTEGER PRIMARY KEY", "INTEGER", "TEXT", "BLOB"),
        Dialect::Postgres => (
            "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
            "BIGINT",
            "TEXT COLLATE \"C\"",
            "BYTEA",
        ),
    };
    let column_defs = |level: Level| -> String {
        attrs::indexed(level)
            .map(|a| match a.kind {
                Kind::Uid if a.level == level && is_own_uid(a.column) => {
                    format!("{} {text} NOT NULL UNIQUE,", a.column)
                }
                Kind::Integer => format!("{} {int},", a.column),
                Kind::PersonName => format!("{0} {text}, {0}_key {text},", a.column),
                _ => format!("{} {text},", a.column),
            })
            .collect()
    };
    let indexes = |level: Level| -> String {
        attrs::indexed(level)
            .filter(|a| !is_own_uid(a.column))
            .map(|a| {
                let column = match a.kind {
                    Kind::PersonName => format!("{}_key", a.column),
                    _ => a.column.to_owned(),
                };
                // Parent keys make the index covering for searches at upper levels.
                let parents = match level {
                    Level::Study => "",
                    Level::Series => ", study_pk",
                    Level::Instance => ", study_pk, series_pk",
                };
                format!(
                    "CREATE INDEX {0}_{column} ON {0}({column}{parents});",
                    level.table()
                )
            })
            .collect()
    };
    format!(
        "CREATE TABLE studies (
            pk {pk},
            {study}
            modalities {text} NOT NULL DEFAULT '',
            num_series {int} NOT NULL DEFAULT 0,
            num_instances {int} NOT NULL DEFAULT 0,
            attrs {blob} NOT NULL,
            rep_instance {int},
            created_at {int} NOT NULL
        );
        CREATE TABLE series (
            pk {pk},
            study_pk {int} NOT NULL,
            {series}
            num_instances {int} NOT NULL DEFAULT 0,
            attrs {blob} NOT NULL,
            rep_instance {int},
            created_at {int} NOT NULL
        );
        CREATE TABLE instances (
            pk {pk},
            series_pk {int} NOT NULL,
            study_pk {int} NOT NULL,
            {instance}
            transfer_syntax {text} NOT NULL,
            frames {int} NOT NULL,
            path {text} NOT NULL,
            size {int} NOT NULL,
            crc32 {int} NOT NULL,
            pixel {blob},
            attrs {blob} NOT NULL,
            metadata {blob} NOT NULL,
            created_at {int} NOT NULL
        );
        CREATE INDEX series_study ON series(study_pk, series_number);
        CREATE INDEX instances_series ON instances(series_pk, instance_number);
        CREATE INDEX instances_study ON instances(study_pk);
        CREATE INDEX instances_path ON instances(path, size, crc32);
        CREATE INDEX studies_created_at ON studies(created_at, pk);
        {study_indexes}{series_indexes}{instance_indexes}",
        study = column_defs(Level::Study),
        series = column_defs(Level::Series),
        instance = column_defs(Level::Instance),
        study_indexes = indexes(Level::Study),
        series_indexes = indexes(Level::Series),
        instance_indexes = indexes(Level::Instance),
    )
}

/// Remote application entities registered at runtime (see [`crate::modalities`]).
fn modalities_ddl(dialect: Dialect) -> String {
    let (int, text) = match dialect {
        Dialect::Sqlite => ("INTEGER", "TEXT"),
        Dialect::Postgres => ("BIGINT", "TEXT COLLATE \"C\""),
    };
    format!(
        "CREATE TABLE modalities (
            ae_title {text} PRIMARY KEY,
            host {text} NOT NULL,
            port {int} NOT NULL,
            description {text} NOT NULL DEFAULT '',
            created_at {int} NOT NULL
        );"
    )
}

/// The UID identifying rows of a table (`study_uid`, `series_uid`, `sop_uid`).
fn is_own_uid(column: &str) -> bool {
    matches!(column, "study_uid" | "series_uid" | "sop_uid")
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn schema_applies_and_is_idempotent() {
        let mut conn = Connection::Sqlite(rusqlite::Connection::open_in_memory().unwrap());
        migrate(&mut conn).unwrap();
        migrate(&mut conn).unwrap();
        let count = conn
            .query_row(
                "SELECT count(*) FROM sqlite_master WHERE type = 'index'",
                &[],
                |r| r.i64(0),
            )
            .unwrap()
            .unwrap();
        assert!(count > 20, "{count} indexes");
        assert_eq!(columns(Level::Study)[0], "study_uid");
        assert!(columns(Level::Study).contains(&"patient_name_key".to_owned()));
    }

    #[test]
    fn version_4_is_upgraded() {
        let mut conn = Connection::Sqlite(rusqlite::Connection::open_in_memory().unwrap());
        migrate(&mut conn).unwrap();
        conn.batch("DROP TABLE modalities; PRAGMA user_version = 4")
            .unwrap();
        migrate(&mut conn).unwrap();
        let version = conn.query_row("PRAGMA user_version", &[], |r| r.i64(0));
        assert_eq!(version.unwrap(), Some(VERSION));
        let count = conn.query_row("SELECT count(*) FROM modalities", &[], |r| r.i64(0));
        assert_eq!(count.unwrap(), Some(0));
    }

    #[test]
    fn other_versions_are_refused() {
        let mut conn = Connection::Sqlite(rusqlite::Connection::open_in_memory().unwrap());
        migrate(&mut conn).unwrap();
        conn.batch("PRAGMA user_version = 3").unwrap();
        let error = migrate(&mut conn).unwrap_err().to_string();
        assert!(error.contains("re-create the index"), "{error}");
    }
}
